/* English build of the tracker for the one Sawa English app.
   node tools/i18n.js extract  → tools/ar-strings.json (Arabic text in app.js and the server messages)
   node tools/i18n.js build    → assets/app-en.js (app.js with every Arabic string replaced from tools/en.json)
   Strings are found with a small JS scanner (quotes, escapes, comments, regex literals), and replaced by position. */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const AR = /[؀-ۿ]/;

/** All string literals in JS source: [{start, end, quote, value}] (start/end include the quotes). */
function scanJs(src) {
	const out = [];
	let i = 0, prev = '';
	while (i < src.length) {
		const c = src[i], n = src[i + 1];
		if (c === '/' && n === '/') { i = src.indexOf('\n', i); if (i < 0) break; continue; }
		if (c === '/' && n === '*') { i = src.indexOf('*/', i + 2) + 2; continue; }
		if (c === "'" || c === '"' || c === '`') {
			const q = c, s = i;
			i++;
			while (i < src.length && src[i] !== q) { if (src[i] === '\\') i++; i++; }
			out.push({ start: s, end: i + 1, quote: q, value: src.slice(s + 1, i) });
			i++; prev = 'x';
			continue;
		}
		if (c === '/' && /[(,=:[!&|?{};+\-*%<>~^]$|^$|return$|typeof$/.test(prev)) {
			// regex literal
			i++;
			let cls = false;
			while (i < src.length) {
				if (src[i] === '\\') { i += 2; continue; }
				if (src[i] === '[') cls = true; else if (src[i] === ']') cls = false; else if (src[i] === '/' && !cls) break;
				i++;
			}
			i++;
			while (/[a-z]/i.test(src[i] || '')) i++;
			prev = 'x';
			continue;
		}
		if (!/\s/.test(c)) prev = /[\w$]/.test(c) ? (/[\w$]/.test(prev.slice(-1)) ? prev + c : c) : c;
		i++;
	}
	return out;
}

function phpStrings(src) {
	const out = [];
	const re = /'((?:[^'\\]|\\.)*)'/g;
	let m;
	while ((m = re.exec(src))) out.push(m[1].replace(/\\'/g, "'"));
	return out;
}

const cmd = process.argv[2];
const appSrc = fs.readFileSync(path.join(ROOT, 'assets/app.js'), 'utf8');
if (cmd === 'extract') {
	const js = [...new Set(scanJs(appSrc).filter((t) => AR.test(t.value)).map((t) => t.value))];
	const php = [];
	for (const f of ['class-rest.php', 'class-rest-social.php', 'class-social.php', 'class-game.php']) {
		phpStrings(fs.readFileSync(path.join(ROOT, 'includes', f), 'utf8')).forEach((s) => { if (AR.test(s) && php.indexOf(s) < 0) php.push(s); });
	}
	fs.writeFileSync(path.join(__dirname, 'ar-strings.json'), JSON.stringify({ js, php }, null, 1));
	console.log('js', js.length, 'php', php.length);
} else if (cmd === 'build') {
	const en = JSON.parse(fs.readFileSync(path.join(__dirname, 'en.json'), 'utf8'));
	const toks = scanJs(appSrc).filter((t) => AR.test(t.value));
	let out = '', last = 0, missing = 0;
	for (const t of toks) {
		const tr = en.js[t.value];
		out += appSrc.slice(last, t.start);
		if (tr == null) { missing++; out += appSrc.slice(t.start, t.end); }
		else out += t.quote + (t.quote === "'" ? tr.replace(/\\?'/g, "\\'") : t.quote === '"' ? tr.replace(/\\?"/g, '\\"') : tr) + t.quote;
		last = t.end;
	}
	out += appSrc.slice(last);
	// English layout and number format; server messages translated at runtime.
	out = out.replace(/dir="rtl" lang="ar"/g, 'dir="ltr" lang="en"').replace(/dir=\\"rtl\\" lang=\\"ar\\"/g, 'dir=\\"ltr\\" lang=\\"en\\"');
	out = out.replace(/var LOC = '[^']*'/, "var LOC = 'en-US'");
	out = out.replace("'use strict';", () => "'use strict';\n  var SERVER_EN = " + JSON.stringify(en.php || {}) + ";\n  function srvEn(m) { m = String(m || ''); if (SERVER_EN[m]) return SERVER_EN[m]; for (var k in SERVER_EN) { if (k.indexOf('%') >= 0) { var re = new RegExp('^' + k.replace(/[.*+?^${}()|[\\]\\\\]/g, '\\\\$&').replace(/%[ds]/g, '(.+?)') + '$'); var x = m.match(re); if (x) { var i = 1; return SERVER_EN[k].replace(/%[ds]/g, function () { return x[i++]; }); } } } return m; }");
	out = out.replace(/throw new Error\(\(j && j\.message\) \|\| /, 'throw new Error(srvEn((j && j.message) || ');
	out = out.replace(/srvEn\(\(j && j\.message\) \|\| ('[^']*')\);/, 'srvEn((j && j.message) || $1));');
	out = '/* GENERATED by tools/i18n.js build from app.js — English version for the one Sawa English app. Do not edit. */\n' + out;
	fs.writeFileSync(path.join(ROOT, 'assets/app-en.js'), out);
	console.log('replaced', toks.length - missing, 'missing', missing);
}
